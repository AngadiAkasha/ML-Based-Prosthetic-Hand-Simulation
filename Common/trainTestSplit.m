function trainTestSplit()
% TRAINTESTSPLIT
% DB1 train/test split using the actual variables stored in AllFeatures.mat
%
% AllFeatures.mat contains:
%   allFeat : 50744 x 10  -> RMS features
%   allRep  : 50744 x 1  -> repetition information
%   allStim : 50744 x 1  -> movement/class labels
%
% Current experiment:
%   ALL AVAILABLE DB1 MOVEMENT CLASSES
%
% The code automatically checks the labels present in allStim.

clc;
clear;
close all;

fprintf('\n============================================\n');
fprintf(' DB1 TRAIN / TEST SPLIT\n');
fprintf('============================================\n');

%% ============================================================
% LOAD ALL FEATURES
% =============================================================

inputFile = 'AllFeatures.mat';

if ~isfile(inputFile)

    error(['AllFeatures.mat not found.\n' ...
           'Current folder:\n%s'],pwd);

end

S = load(inputFile);

fprintf('\nLoaded: %s\n',inputFile);

%% ============================================================
% CHECK REQUIRED VARIABLES
% =============================================================

requiredVariables = {'allFeat','allStim','allRep'};

for i = 1:numel(requiredVariables)

    if ~isfield(S,requiredVariables{i})

        error('Required variable "%s" was not found.', ...
            requiredVariables{i});

    end

end

%% ============================================================
% READ VARIABLES
% =============================================================

features = double(S.allFeat);

labels = double(S.allStim(:));

repetitions = double(S.allRep(:));

%% ============================================================
% DISPLAY DATA INFORMATION
% =============================================================

fprintf('\n============================================\n');
fprintf(' INPUT DATA INFORMATION\n');
fprintf('============================================\n');

fprintf('Feature matrix : %d x %d\n', ...
    size(features,1),size(features,2));

fprintf('Label vector   : %d x 1\n', ...
    numel(labels));

fprintf('Repetition     : %d x 1\n', ...
    numel(repetitions));

%% ============================================================
% CHECK DIMENSIONS
% =============================================================

if size(features,1) ~= numel(labels)

    error(['Feature and label sample counts do not match.\n' ...
           'Features = %d\n' ...
           'Labels   = %d'], ...
           size(features,1),numel(labels));

end

if numel(labels) ~= numel(repetitions)

    error(['Label and repetition counts do not match.\n' ...
           'Labels      = %d\n' ...
           'Repetitions = %d'], ...
           numel(labels),numel(repetitions));

end

%% ============================================================
% REMOVE INVALID SAMPLES
% =============================================================

valid = ...
    all(isfinite(features),2) & ...
    isfinite(labels) & ...
    isfinite(repetitions);

features = features(valid,:);

labels = labels(valid);

repetitions = repetitions(valid);

fprintf('\nValid samples after cleaning: %d\n', ...
    size(features,1));

%% ============================================================
% SHOW ALL LABELS
% =============================================================

allClasses = unique(labels);

fprintf('\n============================================\n');
fprintf(' ORIGINAL DB1 LABELS\n');
fprintf('============================================\n');

fprintf('Number of unique labels = %d\n', ...
    numel(allClasses));

fprintf('Labels:\n');

disp(allClasses');

%% ============================================================
% CLASS DISTRIBUTION
% =============================================================

fprintf('\n============================================\n');
fprintf(' CLASS DISTRIBUTION\n');
fprintf('============================================\n');

for i = 1:numel(allClasses)

    n = sum(labels == allClasses(i));

    fprintf('Class %g : %d samples\n', ...
        allClasses(i),n);

end

%% ============================================================
% SELECT ALL AVAILABLE MOVEMENT CLASSES
% ============================================================
%
% IMPORTANT:
%
% We do NOT assume that the labels are necessarily 1:52.
%
% Instead, we use the actual labels present in allStim.
%
% This is safer because AllFeatures.mat is the actual output
% generated by your feature-extraction program.

selectedClasses = allClasses;

fprintf('\n============================================\n');
fprintf(' SELECTED CLASSES\n');
fprintf('============================================\n');

fprintf('Number of selected classes = %d\n', ...
    numel(selectedClasses));

disp(selectedClasses');

%% ============================================================
% FILTER DATA
% =============================================================

classMask = ismember(labels,selectedClasses);

features = features(classMask,:);

labels = labels(classMask);

repetitions = repetitions(classMask);

%% ============================================================
% VERIFY CLASS COUNT
% =============================================================

usedClasses = unique(labels);

fprintf('\n============================================\n');
fprintf(' FINAL CLASS INFORMATION\n');
fprintf('============================================\n');

fprintf('Number of classes = %d\n', ...
    numel(usedClasses));

disp(usedClasses');

%% ============================================================
% RANDOM STRATIFIED TRAIN / TEST SPLIT
% ============================================================
%
% 80% training
% 20% testing
%
% The split is performed separately for each class so that
% every class is represented in both sets.

rng(42);

trainRatio = 0.80;

trainIndex = false(size(labels));

testIndex = false(size(labels));

for i = 1:numel(usedClasses)

    classIndex = find(labels == usedClasses(i));

    % Randomize samples belonging to this class
    classIndex = classIndex(randperm(numel(classIndex)));

    nSamples = numel(classIndex);

    nTrain = floor(trainRatio*nSamples);

    % Make sure at least one sample remains for testing
    nTrain = min(nTrain,nSamples-1);

    if nTrain < 1

        error('Class %g does not contain enough samples.', ...
            usedClasses(i));

    end

    trainIndex(classIndex(1:nTrain)) = true;

    testIndex(classIndex(nTrain+1:end)) = true;

end

%% ============================================================
% CREATE TRAINING DATA
% =============================================================

trainFeat = features(trainIndex,:);

trainLabel = labels(trainIndex);

trainRep = repetitions(trainIndex);

%% ============================================================
% CREATE TESTING DATA
% =============================================================

testFeat = features(testIndex,:);

testLabel = labels(testIndex);

testRep = repetitions(testIndex);

%% ============================================================
% VERIFY TRAIN / TEST CLASSES
% =============================================================

trainClasses = unique(trainLabel);

testClasses = unique(testLabel);

fprintf('\n============================================\n');
fprintf(' TRAIN / TEST INFORMATION\n');
fprintf('============================================\n');

fprintf('Training samples : %d\n', ...
    size(trainFeat,1));

fprintf('Testing samples  : %d\n', ...
    size(testFeat,1));

fprintf('Training classes : %d\n', ...
    numel(trainClasses));

fprintf('Testing classes  : %d\n', ...
    numel(testClasses));

%% ============================================================
% CHECK THAT EVERY CLASS EXISTS IN BOTH SETS
% =============================================================

missingTrain = setdiff(usedClasses,trainClasses);

missingTest = setdiff(usedClasses,testClasses);

if ~isempty(missingTrain)

    error('These classes are missing from training data: %s', ...
        mat2str(missingTrain'));

end

if ~isempty(missingTest)

    error('These classes are missing from testing data: %s', ...
        mat2str(missingTest'));

end

%% ============================================================
% SAVE TRAINING DATA
% =============================================================

save('TrainData.mat', ...
    'trainFeat', ...
    'trainLabel', ...
    'trainRep', ...
    '-v7.3');

%% ============================================================
% SAVE TEST DATA
% =============================================================

save('TestData.mat', ...
    'testFeat', ...
    'testLabel', ...
    'testRep', ...
    '-v7.3');

%% ============================================================
% FINAL SUMMARY
% =============================================================

fprintf('\n============================================\n');
fprintf(' TRAIN / TEST SPLIT COMPLETE\n');
fprintf('============================================\n');

fprintf('Total samples     : %d\n', ...
    size(features,1));

fprintf('Number of classes : %d\n', ...
    numel(usedClasses));

fprintf('Training samples  : %d\n', ...
    size(trainFeat,1));

fprintf('Testing samples   : %d\n', ...
    size(testFeat,1));

fprintf('Training ratio    : %.2f %%\n', ...
    100*size(trainFeat,1)/size(features,1));

fprintf('Testing ratio     : %.2f %%\n', ...
    100*size(testFeat,1)/size(features,1));

fprintf('\nTrainData.mat saved successfully.\n');

fprintf('TestData.mat saved successfully.\n');

fprintf('\n============================================\n');

end